const DICTS = { ru, en } as const;
export type Lang = keyof typeof DICTS;

export function makeRadarT(lang: string) {
  const dict = DICTS[lang === 'en' ? 'en' : 'ru'];
  return (key: RadarKey, vars?: Record<string, string | number>): string =>
    vars ? dict[key].replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : '')) : dict[key];
}
export type RadarT = ReturnType<typeof makeRadarT>;

export const levelKey = (l: RiskLevel): RadarKey => `level_${l}`;
export const actionKey = (a: ActionCode): RadarKey => `act_${a}`;
export const actionSubKey = (a: ActionCode): RadarKey => `act_${a}_s` as RadarKey;
export const reasonKey = (c: ReasonCode): RadarKey => `reason_${c}`;

/** Russian plural for "работа/работы/работ". */
export function worksWord(n: number, t: RadarT): string {
  const mod10 = n % 10, mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return t('works1');
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return t('works2');
  return t('works5');
}
